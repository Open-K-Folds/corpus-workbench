import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {readFileSync, readdirSync} from 'node:fs';
import {join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {extractFile, listPackage} from '@electron/asar';
import packaging from './package.cjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const [directory, binary] = process.argv.slice(2);
assert.ok(directory && binary, 'Supply the packaged Windows directory and its freshly built sidecar.');
const base = join(root, 'node_modules/electron/dist');
const app = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const digest = file => sha(readFileSync(file));
const git = (...args) => execFileSync('git', args, {cwd:root, encoding:'utf8'}).trim();

function files(dir, prefix = '') {
  return readdirSync(join(dir, prefix), {withFileTypes:true}).flatMap(entry => {
    const name = prefix + entry.name;
    if (entry.isDirectory()) return files(dir, name + '/');
    assert.ok(entry.isFile(), 'Unexpected linked or special file: ' + name);
    return [name];
  });
}

const expected = new Map();
for (const name of files(base)) {
  if (name === 'electron.exe' || name === 'resources/default_app.asar') continue;
  expected.set(name, digest(join(base, name)));
}
expected.set(app.productName + '.exe', null); // Packager brands Electron's PE resources.
expected.set('LICENSE.workbench', digest(join(root, 'LICENSE')));
expected.set('NOTICE.workbench', digest(join(root, 'NOTICE')));
expected.set('resources/backend/corpus-workbench.exe', digest(resolve(binary)));
expected.set('resources/semantica/semantica-handoff.py', digest(join(root,'scripts/semantica-handoff.py')));
expected.set('resources/icon.png', digest(join(root, 'desktop/resources/icon.png')));
for (const name of files(join(root, 'ui/dist'))) expected.set('resources/ui/' + name, digest(join(root, 'ui/dist', name)));
for (const name of git('ls-files', 'fixtures/synthetic', 'fixtures/coanalysis/xmlfiles').split(/\r?\n/)) {
  expected.set(name.replace(/^fixtures\/(synthetic|coanalysis)\//, 'resources/demo/'), digest(join(root, name)));
}
// Eight seconds of the 220 Hz mono tone generated by desktop/build.cjs.
expected.set('resources/demo/Audio/synthetic-workbench.wav', '13754d6447263ec7ac799ac3377bb51c2e3de8fd2cd70d31b645ef2a2d768da5');
expected.set('resources/app.asar', null);
expected.set('local-build.json', null);
assert.deepEqual(files(directory).sort(), [...expected.keys()].sort(), 'Unexpected or missing Windows package files');
for (const [name, hash] of expected) if (hash) assert.equal(digest(join(directory, name)), hash, name);

const asar = join(directory, 'resources/app.asar');
const sources = packaging.desktopSources.map(name => 'desktop/' + name);
assert.deepEqual(listPackage(asar).map(name => name.replaceAll('\\','/').replace(/^\//,'')).sort(),
  ['desktop', 'package.json', ...sources].sort());
for (const name of sources) assert.equal(sha(extractFile(asar, name)), digest(join(root, name)), name);
const {name, productName, version, description, author, license, main} = app;
assert.deepEqual(JSON.parse(extractFile(asar, 'package.json')), {name, productName, version, description, author, license, main});
assert.deepEqual(JSON.parse(readFileSync(join(directory, 'local-build.json'))), {application:productName, version, platform:'win32',
  architecture:'x64', electron:app.devDependencies.electron, sourceCommit:git('rev-parse','HEAD'), sourceDirty:false,
  signed:false, backend:expected.get('resources/backend/corpus-workbench.exe')});
assert.equal(readFileSync(join(directory,'version'),'utf8').trim(), app.devDependencies.electron);
console.log('Verified Windows runtime, application archive, compiled UI, sidecar and synthetic practice files.');
